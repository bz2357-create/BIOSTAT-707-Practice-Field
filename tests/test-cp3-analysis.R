library(data.table)
for(f in c('load-set-a','audit-missingness','build-wide','cp2-data','cp2-preprocess','cp2-models','cp3-data','cp3-metrics')) source(paste0('R/',f,'.R'))
if(file.exists('R/cp3-analysis.R')) source('R/cp3-analysis.R')
stopifnot('CP3 analysis exists'=exists('cp3_contributions'))
b <- cp3_load_bundle();x <- as.data.frame(setNames(lapply(b$preprocess$predictors,function(n) rep(if(n %in% names(b$preprocess$medians)) b$preprocess$medians[n] else 0,4)),b$preprocess$predictors))
x$Age <- c(40,60,80,NA);x$Gender <- c(0,1,NA,99);x$ICUType <- c(1,2,3,4)
c <- cp3_contributions(b,x);stopifnot(max(abs(c$reconstructed_p-cp3_predict(b,x)))<1e-10)
a <- list(y=rep(0:1,6),benchmarks=data.table(SOFA_score=rep(1:6,each=2)))
s <- cp3_sofa_mapping(a);stopifnot(max(abs(plogis(s$coefficients[1]+s$coefficients[2]*1:6)-.5))<1e-6)
y <- c(0,0,1,1);p <- c(.1,.2,.8,.9);bench <- data.table(SAPS_I_score=c(NA,2,3,4),SOFA_score=1:4)
q <- cp3_discrimination(y,p,bench,30,1)
stopifnot(q$summary[population=='Common scores',all(n==3)],q$summary[population=='All stays',n]==4)
g <- cp3_subgroups(data.frame(Age=c(40,40,80,80),Gender=c(0,0,1,1),ICUType=c(1,1,2,2)),y,p,R=30,seed=10)
stopifnot(anyNA(g$auc),all(g$small_group),all(g$n>0))
cat('CP3 analysis fixtures passed: contributions, A-only SOFA, cohorts and undefined subgroups.\n')
# Very large individual contributions should trigger source-scale review even if no hard rule fires.
xx <- x[rep(1,10),];xx$WBC_h24_48_max[1] <- 12500
fake <- list(x=xx,y=rep(0:1,5),ids=as.character(1:10),quality=data.table(missing_fraction=0,hard_invalid=0,untyped_records=0)[rep(1,10)])
ee <- cp3_error_cases(b,fake,cp3_predict(b,xx))
stopifnot(ee$public[case=='Survivor-1',data_review_flag])
