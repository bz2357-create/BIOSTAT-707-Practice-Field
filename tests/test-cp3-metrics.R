library(data.table);source('R/cp2-preprocess.R')
if(file.exists('R/cp3-metrics.R')) source('R/cp3-metrics.R')
stopifnot('CP3 metrics exist'=exists('cp3_auc_boot'))
y <- c(0,0,1,1);p <- c(.1,.2,.8,.9)
a <- cp3_auc_boot(y,p,30,123); stopifnot(a$auc==1,a$lower==1,a$upper==1,identical(a$draws,cp3_auc_boot(y,p,30,123)$draws))
stopifnot(cp3_auc_boot(y,1-p,30,1)$auc==0,cp3_auc_boot(y,rep(.5,4),30,1)$auc==.5,is.na(cp3_auc_boot(rep(1,4),p,30,1)$auc))
t <- cp3_threshold(y,p,.2);stopifnot(t$TP==2,t$FP==1,t$FN==0,t$TN==1,t$sensitivity==1,abs(t$PPV-2/3)<1e-12,t$flagged_per_100==75,t$event1==2/3)
stopifnot(is.na(cp3_threshold(y,p,1)$PPV),is.na(cp3_threshold(rep(0,4),p,.2)$sensitivity))
pr <- cp3_pr(y,rep(.5,4));stopifnot(pr$average_precision==.5,nrow(pr$curve)==2)
d <- cp3_dca(y,p,rep(.5,4),c(.2,.5));stopifnot(abs(d[method=='Model' & threshold==.2,net_benefit]-.4375)<1e-12,d[method=='Treat none',all(net_benefit==0)])
c <- cp3_calibration(y,p,smooth=FALSE);stopifnot(abs(c$summary$brier-.025)<1e-12,abs(c$summary$scaled_brier-.9)<1e-12)
stopifnot(cp3_calibration(y,c(0,.2,.8,1),smooth=FALSE)$summary$clipped==2)
err <- function(e) stopifnot(inherits(try(force(e),silent=TRUE),'try-error'))
err(cp3_threshold(y,c(-.1,.2,.8,.9),.2));err(cp3_auc_boot(y,c(.1,NA,.8,.9),30,1))
cat('CP3 metric fixtures passed: direction, bootstrap, ties, PR, NB, Brier and undefined denominators.\n')
